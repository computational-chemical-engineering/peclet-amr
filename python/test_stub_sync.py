"""Contract: the shipped type stub packaging/_amr.pyi covers every public name of peclet.amr._amr.

The stub is generated by nanobind.stubgen against a host build (recipe in CMakeLists.txt and
CLAUDE.md: `python -m nanobind.stubgen -m peclet.amr._amr -o packaging/_amr.pyi`). A binding added
without regenerating it fails here, and so does a name in the stub that the extension no longer
defines. amr always links MPI, so no name is build-dependent.

Run: PYTHONPATH=<build> python -m pytest -q python/test_stub_sync.py (ctest python_stub_sync)
"""
import ast
from pathlib import Path

from peclet.amr import _amr

STUB = Path(__file__).resolve().parents[1] / "packaging" / "_amr.pyi"


def _public(name):
    return not name.startswith("_") or name == "__init__"


def _top_level_name(node):
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
        return node.name
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return node.target.id
    return None


def _member_names(cls):
    return {f"{cls.name}.{m.name}" for m in cls.body
            if isinstance(m, ast.FunctionDef) and _public(m.name)}


def _stub_names():
    tree = ast.parse(STUB.read_text())
    names = {_top_level_name(node) for node in tree.body} - {None}
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            names |= _member_names(node)
    return names


def _runtime_names():
    names = set()
    for name in dir(_amr):
        if name.startswith("_"):
            continue
        names.add(name)
        obj = getattr(_amr, name)
        if isinstance(obj, type):
            # A class without a bound constructor (FlowDiagnostics) still has nanobind's refusing
            # __init__, which carries no signature and is not part of the API.
            names.update(f"{name}.{m}" for m, v in vars(obj).items()
                         if _public(m) and (m != "__init__" or hasattr(v, "__nb_signature__")))
    return names


def test_stub_covers_every_public_name():
    missing = sorted(_runtime_names() - _stub_names())
    assert not missing, (f"public names of peclet.amr._amr missing from {STUB.name}: {missing}; "
                         "regenerate the stub (recipe in CMakeLists.txt)")


def test_stub_names_exist_at_runtime():
    extra = sorted(_stub_names() - _runtime_names())
    assert not extra, f"names in {STUB.name} that peclet.amr._amr does not define: {extra}"
